import assert from 'node:assert/strict';
import {projectEvent} from '../plugins/dsh-guga-desktop/index.mjs';
const s={id:'session-a'};
let state=projectEvent(s,{type:'user/message',data:{content:[{type:'text',text:'打开浏览器'}]}});
state=projectEvent(s,{type:'turn/start',data:{turn:1}},state);
assert.equal(state.goal,'打开浏览器');assert.equal(state.state,'running');
state=projectEvent(s,{type:'tool/call',data:{name:'mcp__guga__applications'}},state);
assert.equal(state.tool,'mcp__guga__applications');
assert.equal(projectEvent(s,{type:'assistant/message',data:{content:'PRIVATE_REASONING'}},state),null);
assert.equal(projectEvent(s,{type:'tool/result',surfaceOp:'replace',data:{}},state),null);
const end=projectEvent(s,{type:'turn/end',data:{reason:'error'}},state);
assert.equal(end.state,'failed');assert.equal(end.session_id,'session-a');
const other=projectEvent({id:'session-b'},{type:'turn/start',data:{turn:1}});
assert.equal(other.goal,undefined);
assert.equal(projectEvent(s,{type:'turn/end',data:{reason:'cancelled'}},state).state,'cancelled');
const publicReply=projectEvent(s,{type:'assistant/message',data:{message:{content:[{type:'reasoning',text:'SECRET_CHAIN'},{type:'text',text:'浏览器已经打开'}]}}},state);
assert.ok(publicReply.summary.includes('浏览器已经打开'));
assert.ok(!JSON.stringify(publicReply).includes('SECRET_CHAIN'));
console.log(JSON.stringify({ok:true,checks:10,reasoning_forwarded:false}));
